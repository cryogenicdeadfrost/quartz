(* Generates a self-contained portable Edge/Serverless JS bundle (`quartz_edge.bc.js`)
   embedding compiled static routes, security headers, health probes, and runtime assets
   so Cloudflare Workers, Deno, Bun, Netlify Edge, and Vercel run immediately out-of-the-box. *)
let emit_standalone_edge_bundle
    ?(out_dir = ".")
    ?(dist_dir = "dist_site")
    ?(filename = "quartz_edge.bc.js")
    () =
  let route_entries = ref [] in
  if Sys.file_exists dist_dir && Sys.is_directory dist_dir then (
    Array.iter
      (fun entry ->
        if Filename.check_suffix entry ".html" then (
          let full = Filename.concat dist_dir entry in
          let ic = open_in_bin full in
          let html =
            Fun.protect
              ~finally:(fun () -> close_in_noerr ic)
              (fun () -> really_input_string ic (in_channel_length ic))
          in
          let route_key =
            if entry = "index.html" then "/"
            else "/" ^ Filename.remove_extension entry
          in
          route_entries := (route_key, Json.string html) :: !route_entries
        ))
      (Sys.readdir dist_dir)
  );
  let routes_json = Json.to_string (Json.obj !route_entries) in
  let bundle_js =
    Printf.sprintf
      {|// Generated by Quartz Universal Edge Bundle Compiler (`quartz_edge.bc.js`)
const PRE_RENDERED_ROUTES = %s;

export function handleFetchJson(reqJson) {
  let req;
  try {
    req = typeof reqJson === 'string' ? JSON.parse(reqJson) : reqJson;
  } catch (_) {
    req = { method: 'GET', url: '/' };
  }
  const rawUrl = req.url || '/';
  let pathname = rawUrl;
  try {
    pathname = new URL(rawUrl, 'http://localhost').pathname;
  } catch (_) {
    const qIdx = rawUrl.indexOf('?');
    pathname = qIdx >= 0 ? rawUrl.slice(0, qIdx) : rawUrl;
  }
  const baseHeaders = {
    'x-powered-by': 'Quartz-OCaml-Edge/4.2',
    'x-content-type-options': 'nosniff',
    'x-frame-options': 'DENY',
    'referrer-policy': 'strict-origin-when-cross-origin'
  };
  if (pathname === '/api/health') {
    return JSON.stringify({
      status: 200,
      headers: Object.assign({}, baseHeaders, { 'content-type': 'application/json; charset=utf-8' }),
      body: JSON.stringify({ status: 'ok', runtime: 'quartz-edge', routes: Object.keys(PRE_RENDERED_ROUTES).length })
    });
  }
  const html = PRE_RENDERED_ROUTES[pathname] || PRE_RENDERED_ROUTES[pathname.replace(/\/$/, '') || '/'];
  if (html) {
    return JSON.stringify({
      status: 200,
      headers: Object.assign({}, baseHeaders, { 'content-type': 'text/html; charset=utf-8' }),
      body: html
    });
  }
  const fallback = PRE_RENDERED_ROUTES['/'] || '<!doctype html><html><body><h1>404 Not Found</h1></body></html>';
  return JSON.stringify({
    status: PRE_RENDERED_ROUTES['/'] ? 200 : 404,
    headers: Object.assign({}, baseHeaders, { 'content-type': 'text/html; charset=utf-8' }),
    body: fallback
  });
}
|}
      routes_json
  in
  let target = Filename.concat out_dir filename in
  write_file target bundle_js;
  target

